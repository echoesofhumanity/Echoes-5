'use strict';
const assert=require('node:assert/strict');
const {create,CAPACITY,EVENTS}=require('../academy/classroom/classroom-demo-engine.js');
const room=create({capacity:2});
assert.equal(CAPACITY,12);
assert.equal(room.snapshot().mode,'synthetic-local-only');
assert.throws(()=>room.decide('a',true,'student'),/instructor/);
assert.throws(()=>room.hand('a',true),/Not admitted/);
room.request('a');
assert.throws(()=>room.request('a'),/Already/);
assert.throws(()=>room.decide('a',true,'student'),/instructor/);
room.decide('a',true,'instructor');
room.request('b');room.decide('b',true,'instructor');
room.request('c');
assert.throws(()=>room.decide('c',true,'instructor'),/full/);
assert.equal(room.snapshot().seats,2);
room.hand('a',true);
room.grant('a','instructor');
assert.equal(room.snapshot().speaker,'a');
assert.throws(()=>room.grant('b','instructor'),/queued|active/);
room.remove('a','instructor');
assert.equal(room.snapshot().speaker,null);
assert.equal(room.snapshot().seats,1);
assert.equal(room.snapshot().participants.find(p=>p.id==='a').state,'removed');
room.request('a');room.decide('a',false,'instructor');
assert.equal(room.snapshot().participants.find(p=>p.id==='a').state,'denied');
room.request('a');room.decide('a',true,'instructor');
room.hand('a',true);room.grant('a','instructor');room.revoke('instructor');
room.end('instructor');
assert.throws(()=>room.request('d'),/ended/);
const ev=room.snapshot().events;
assert.equal(ev[0].type,EVENTS.REQUEST);
assert.equal(ev.at(-1).type,EVENTS.END);
assert.deepEqual(ev.map(e=>e.sequence),ev.map((_,i)=>i+1));
assert.ok(ev.every(e=>e.schema_version===1&&e.session_id==='synthetic-classroom'));
console.log('Academy synthetic classroom contract: PASS');
